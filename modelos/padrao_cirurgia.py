"""Os modelos de solicitação de cirurgia do sistema.

Vieram dos arquivos do Dr. Fernando Freua (2026-11-12): o guia de como
deve ser uma solicitação de cirurgia e as duas tabelas de codificação —
crânio, hidrocefalia e nervo periférico, e coluna. Moram em código pelo
mesmo motivo dos outros modelos do sistema (`modelos/padrao.py`).

O que foi feito com o texto dos arquivos, e só isto:

- cada código TUSS e cada CID foi conferido contra os catálogos do sistema,
  e a descrição que vai no modelo é a **oficial** (a da tabela), não a
  digitada; `check_modelos_cirurgia` reprova código que não exista;
- dois códigos errados foram corrigidos, com autorização do autor: a
  monitorização neurofisiológica dos modelos de coluna estava como
  2.02.02.03-2, que na TUSS é *monitorização hemodinâmica invasiva* (o
  certo, 2.02.02.04-0, é o que os modelos de crânio já usavam), e o tumor
  intradural trazia 3.07.15.35-9, que não existe, ao lado do certo
  3.07.15.35-0;
- "(N)" virou quantidade 1, que o cirurgião ajusta na caixa de setas;
- o substituto de dura-máter, o kit Neuropulse e o hemostático Floseal,
  escritos como subtítulos, viraram linhas de material;
- a lista de empresas virou a sugestão dos três campos de fornecedor
  (`estrutura.FORNECEDORES_SUGERIDOS`), e não um texto do modelo;
- "Tumor hipófise com invasão do seio cavernoso" aparecia só como título,
  sem conteúdo, e ficou de fora até ser escrito.

A justificativa traz o roteiro do guia (história, exame neurológico,
neuroimagem) com `[completar]` onde vai o caso; a emissão recusa o texto
que ainda o tiver.
"""

